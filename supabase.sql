-- Run this in Supabase SQL Editor.
create table if not exists public.tabassum_responses (
  id bigint generated by default as identity primary key,
  verdict text,
  complaint_reply text,
  quiz_answers jsonb,
  love_choice text,
  message text,
  relationship text,
  special_message text,
  submitted_at timestamptz default now()
);

alter table public.tabassum_responses enable row level security;

-- Public visitors may submit responses, but cannot read the table.
create policy "Allow anonymous submissions"
on public.tabassum_responses
for insert
to anon
with check (true);

